"""Write the data files for the two local web pages in web/.

- web/clips.js: the blind listening clips (systems A-D, listening seeds) for web/listening.html.
- web/generation_data.js: real generation runs (model's top combinations, probabilities, constraint,
  pick) for web/generation.html, for every system x seed x temperature option. The detailed view's data
  (LSTM outputs, cell states, all 512 probabilities) is included for temperature 1.0 only, the
  temperature the experiments use, to keep the file small.

Data is written as JS files (not JSON) so the pages work when opened directly from disk.
Run from the project root: .venv/bin/python -m src.export_web
"""
import base64
import json

import numpy as np
import torch

from src.config import LISTEN_SEEDS, ROOT, TEMPERATURES_QUALITATIVE, TRAIN_SEEDS
from src.generate import lstm_loop
from src.model import from_combo, to_combo
from src.train import load_model

WEB = ROOT / "web"
TOP_K = 8
DETAIL_TEMPERATURE = 1.0
CELL_MAX = 128.0  # cell states are stored on a signed log scale up to this magnitude
VIZ_SEEDS = (0, 1, 2)
VIZ_SYSTEMS = {"B": ("base", False, "B · free: the model chooses every drum"),
               "C": ("base", True, "C · constrained: kick and snare follow the skeleton"),
               "D": ("fotf", True, "D · fine-tuned on four-on-the-floor, constrained")}
CLIP_SYSTEMS = {"A": "A rules", "B": "B free", "C": "C constrained", "D": "D fine-tuned"}


def write_js(path, name: str, data) -> None:
    path.write_text(f"// generated by src/export_web.py\nconst {name} = {json.dumps(data, separators=(',', ':'))};\n")


def clips() -> list[dict]:
    """Every blind listening clip that exists in output/audio."""
    out = []
    for letter, system in CLIP_SYSTEMS.items():
        for seed in LISTEN_SEEDS:
            name = f"{letter}_seed{seed}"
            if (ROOT / "output" / "audio" / f"{name}.wav").exists():
                out.append({"id": name, "system": system, "file": f"../output/audio/{name}.wav"})
    return out


def b64(a: np.ndarray) -> str:
    return base64.b64encode(np.ascontiguousarray(a).tobytes()).decode()


def run(model, seed: int, constrained: bool, temperature: float) -> dict:
    """One generation, compressed to what the page shows: per step the top combinations and the pick.

    At the detail temperature also: the LSTM outputs h per layer as int8 (value * 127; they lie in (-1, 1)),
    the cell states c as int8 on a signed log scale (q = 127 * sign(c) * log1p(|c|) / log1p(CELL_MAX)), and
    all 512 probabilities as uint8 on a log scale (q = 255 * (1 + log10(p) / 4), so 1e-4 -> 0 and 1 -> 255).
    """
    gen = lstm_loop(model, seed, constrained, temperature=temperature, record_hidden=True)
    steps = []
    for t in range(len(gen.loop)):
        chosen = int(to_combo(torch.tensor(gen.loop[t])))
        top = list(np.argsort(gen.probs[t])[::-1][:TOP_K])
        if chosen not in top:
            top[-1] = chosen
        steps.append({"top": [[int(c), round(float(gen.probs[t][c]), 4), bool(gen.allowed[t][c])] for c in top],
                      "pick": chosen, "allowedMass": round(float((gen.probs[t] * gen.allowed[t]).sum()), 4)})
    out = {"loop": gen.loop.tolist(), "steps": steps}
    if temperature == DETAIL_TEMPERATURE:
        hidden = np.clip(np.rint(gen.hidden * 127), -127, 127).astype(np.int8)
        cell = np.clip(np.rint(127 * np.sign(gen.cell) * np.log1p(np.abs(gen.cell)) / np.log1p(CELL_MAX)), -127, 127)
        logp = np.log10(np.clip(gen.probs, 1e-4, 1))
        out.update(hidden=b64(hidden), cell=b64(cell.astype(np.int8)),
                   probs=b64(np.rint(255 * (1 + logp / 4)).astype(np.uint8)))
    return out


def main() -> None:
    WEB.mkdir(exist_ok=True)
    write_js(WEB / "clips.js", "CLIPS", clips())
    models = {kind: load_model(kind, TRAIN_SEEDS[0]) for kind in ("base", "fotf")}
    runs = {}
    for key, (kind, constrained, _) in VIZ_SYSTEMS.items():
        for seed in VIZ_SEEDS:
            for temp in TEMPERATURES_QUALITATIVE:
                runs[f"{key}|{seed}|{temp}"] = run(models[kind], seed, constrained, temp)
    combos = [from_combo(torch.tensor(i)).int().tolist() for i in range(512)]
    write_js(WEB / "generation_data.js", "GENERATION", {
        "systems": {k: v[2] for k, v in VIZ_SYSTEMS.items()}, "seeds": list(VIZ_SEEDS),
        "temperatures": list(TEMPERATURES_QUALITATIVE), "trainSeed": TRAIN_SEEDS[0], "combos": combos,
        "layers": models["base"].config["layers"], "units": models["base"].config["hidden"],
        "detailTemperature": DETAIL_TEMPERATURE, "cellMax": CELL_MAX, "runs": runs})
    print(f"wrote {len(clips())} clips and {len(runs)} generation runs to {WEB}")


if __name__ == "__main__":
    main()
